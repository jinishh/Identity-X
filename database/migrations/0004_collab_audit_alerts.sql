-- 0004 · Collaboration, the audit ledger, and alerts.

-- ───────────── collab ─────────────
CREATE TABLE collab.requests (
  id            uuid PRIMARY KEY DEFAULT gen_random_uuid(),
  type          text NOT NULL CHECK (type IN ('SHARE','CUSTODY_TRANSFER','REVIEW','LEGAL_HOLD_RELEASE','MEMBERSHIP')),
  status        text NOT NULL DEFAULT 'PENDING' CHECK (status IN ('PENDING','APPROVED','REJECTED','CANCELLED','EXPIRED')),
  case_id       uuid NOT NULL REFERENCES cases.cases(id),
  document_id   uuid REFERENCES docs.documents(id),
  version_id    uuid REFERENCES docs.versions(id),
  requested_by  uuid NOT NULL REFERENCES iam.users(id),
  assigned_to   uuid REFERENCES iam.users(id),
  payload       jsonb NOT NULL DEFAULT '{}',
  reason        text NOT NULL,
  decided_by    uuid REFERENCES iam.users(id),
  decided_at    timestamptz,
  decision_note text,
  created_at    timestamptz NOT NULL DEFAULT now(),
  CONSTRAINT nobody_approves_their_own_request CHECK (decided_by IS NULL OR decided_by <> requested_by)
);
COMMENT ON TABLE collab.requests IS 'Anything that needs a second officer. The database itself refuses self-approval.';
CREATE INDEX requests_case_idx ON collab.requests(case_id);
CREATE INDEX requests_pending_idx ON collab.requests(status) WHERE status = 'PENDING';

CREATE TABLE collab.shares (
  id              uuid PRIMARY KEY DEFAULT gen_random_uuid(),
  document_id     uuid NOT NULL REFERENCES docs.documents(id),
  grantee_user_id uuid NOT NULL REFERENCES iam.users(id),
  scope           text NOT NULL CHECK (scope IN ('VIEW_REDACTED','VIEW','DOWNLOAD')),
  expires_at      timestamptz NOT NULL,
  request_id      uuid REFERENCES collab.requests(id),
  created_by      uuid NOT NULL REFERENCES iam.users(id),
  approved_by     uuid REFERENCES iam.users(id),
  created_at      timestamptz NOT NULL DEFAULT now(),
  revoked_by      uuid REFERENCES iam.users(id),
  revoked_at      timestamptz,
  revoke_reason   text,
  CONSTRAINT shares_expire_after_creation CHECK (expires_at > created_at)
);
COMMENT ON TABLE collab.shares IS 'Time-limited, scoped access to one document for someone outside the case. Always expires.';
CREATE INDEX shares_grantee_idx ON collab.shares(grantee_user_id) WHERE revoked_at IS NULL;

-- ───────────── audit ─────────────
CREATE TABLE audit.events (
  seq              bigint PRIMARY KEY CHECK (seq >= 1),
  id               uuid NOT NULL UNIQUE,
  occurred_at      timestamptz NOT NULL,
  actor_user_id    uuid,                       -- deliberately no FK: the ledger outlives everything it mentions
  actor_role       text,
  actor_service_id text,
  ip               text,
  user_agent       text,
  action           text NOT NULL,
  outcome          text NOT NULL CHECK (outcome IN ('SUCCESS','DENIED','FAILED')),
  reason_code      text,
  case_id          uuid,
  document_id      uuid,
  version_id       uuid,
  target_user_id   uuid,
  request_id       uuid,
  purpose          text,
  summary          text NOT NULL,
  details          jsonb NOT NULL DEFAULT '{}',
  prev_hash        char(64) NOT NULL,
  event_hash       char(64) NOT NULL UNIQUE
);
COMMENT ON TABLE audit.events IS 'The ledger. event_hash = SHA-256(prev_hash ‖ canonical JSON of the event). Append-only: UPDATE, DELETE and TRUNCATE are rejected by triggers, and the app role is only granted INSERT and SELECT.';
CREATE INDEX events_case_idx ON audit.events(case_id);
CREATE INDEX events_document_idx ON audit.events(document_id);
CREATE INDEX events_actor_idx ON audit.events(actor_user_id);
CREATE INDEX events_action_idx ON audit.events(action);
CREATE INDEX events_time_idx ON audit.events(occurred_at);

CREATE TRIGGER events_append_only BEFORE UPDATE OR DELETE ON audit.events
  FOR EACH ROW EXECUTE FUNCTION public.forbid_change();
CREATE TRIGGER events_no_truncate BEFORE TRUNCATE ON audit.events
  FOR EACH STATEMENT EXECUTE FUNCTION public.forbid_change();

CREATE TABLE audit.checkpoints (
  id             bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  from_seq       bigint NOT NULL,
  to_seq         bigint NOT NULL,
  head_hash      char(64) NOT NULL,
  merkle_root    char(64) NOT NULL,
  event_count    integer NOT NULL,
  created_at     timestamptz NOT NULL,
  signature      bytea NOT NULL,
  signing_key_id text NOT NULL REFERENCES iam.signing_keys(kid),
  sealed_path    text NOT NULL,
  CHECK (to_seq >= from_seq)
);
COMMENT ON TABLE audit.checkpoints IS 'Every 50 events: Merkle root + head hash, Ed25519-signed, and a sealed copy written outside the database. Rewriting the whole chain still fails against these.';
CREATE TRIGGER checkpoints_append_only BEFORE UPDATE OR DELETE ON audit.checkpoints
  FOR EACH ROW EXECUTE FUNCTION public.forbid_change();
CREATE TRIGGER checkpoints_no_truncate BEFORE TRUNCATE ON audit.checkpoints
  FOR EACH STATEMENT EXECUTE FUNCTION public.forbid_change();

-- A quick structural check anyone can run in pgAdmin: rows whose link to the previous row is broken.
-- (Recomputing the hashes themselves needs the canonical JSON encoder — that is POST /audit/verify-chain.)
CREATE VIEW audit.broken_links AS
SELECT e.seq, e.prev_hash, lag(e.event_hash) OVER (ORDER BY e.seq) AS previous_event_hash,
       e.seq - lag(e.seq) OVER (ORDER BY e.seq) AS gap
FROM audit.events e;
CREATE VIEW audit.chain_problems AS
SELECT seq, prev_hash, previous_event_hash, gap FROM audit.broken_links
WHERE (previous_event_hash IS NOT NULL AND prev_hash <> previous_event_hash) OR gap <> 1;
COMMENT ON VIEW audit.chain_problems IS 'Empty when every row points at the one before it with no gaps.';

-- ───────────── alerts ─────────────
CREATE TABLE alerts.alerts (
  id              uuid PRIMARY KEY DEFAULT gen_random_uuid(),
  type            text NOT NULL,
  severity        text NOT NULL CHECK (severity IN ('INFO','LOW','MEDIUM','HIGH','CRITICAL')),
  title           text NOT NULL,
  message         text NOT NULL,
  case_id         uuid,
  document_id     uuid,
  actor_user_id   uuid REFERENCES iam.users(id),
  audit_seq       bigint,
  status          text NOT NULL DEFAULT 'OPEN' CHECK (status IN ('OPEN','ACKNOWLEDGED','RESOLVED')),
  acknowledged_by uuid REFERENCES iam.users(id),
  acknowledged_at timestamptz,
  resolved_by     uuid REFERENCES iam.users(id),
  resolved_at     timestamptz,
  resolution_note text,
  created_at      timestamptz NOT NULL DEFAULT now()
);
CREATE INDEX alerts_open_idx ON alerts.alerts(status) WHERE status <> 'RESOLVED';
